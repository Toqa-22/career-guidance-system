// تجميع سجلات الطلاب حسب القسم مع العدّ، مرتبة تنازلياً حسب عدد المتدربين
function groupStudentsByDepartment(students){
  const counts = {};
  students.forEach(s => {
    if (!s.department) return;
    counts[s.department] = (counts[s.department] || 0) + 1;
  });
  return Object.entries(counts)
    .map(([department, count]) => ({ department, count }))
    .sort((a, b) => b.count - a.count);
}

// صياغة عربية صحيحة لعدد المتدربين (متدرب / متدربان / متدربين)
function formatTraineeCount(n){
  if (n === 1) return "متدرب واحد";
  if (n === 2) return "متدربان";
  if (n >= 3 && n <= 10) return `${n} متدربين`;
  return `${n} متدرب`;
}
